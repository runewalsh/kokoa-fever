#==============================================================================
# ■ Scene_Battle
#------------------------------------------------------------------------------
# 　バトル画面の処理を行うクラスです。
#==============================================================================
class Scene_Battle < Scene_Base
  #--------------------------------------------------------------------------
  # ● 開始処理
  #--------------------------------------------------------------------------
  alias start_log start
  def start
    start_log
    $game_temp.log.clear
  end
  #--------------------------------------------------------------------------
  # ● パーティコマンドウィンドウの作成
  #--------------------------------------------------------------------------
  alias create_party_command_window_log create_party_command_window
  def create_party_command_window
    create_party_command_window_log
    @party_command_window.set_handler(:log, method(:command_log))
    @party_command_window.unselect
  end
  #--------------------------------------------------------------------------
  # ● バックログウィンドウの作成
  #--------------------------------------------------------------------------
  def create_back_log_window
    @back_log_window = Window_BackLog.new
    @back_log_window.set_handler(:ok,     method(:on_log_cancel))
    @back_log_window.set_handler(:cancel, method(:on_log_cancel))
    @back_log_window.deactivate
    @back_log_window.hide
  end
  #--------------------------------------------------------------------------
  # ● ログ［キャンセル］
  #--------------------------------------------------------------------------
  def on_log_cancel
    @back_log_window.deactivate
    @back_log_window.hide
    @back_log_window.clear_background
    @status_window.show
    @party_command_window.activate
    @party_command_window.show
  end
  #--------------------------------------------------------------------------
  # ● コマンド［ログ］
  #--------------------------------------------------------------------------
  def command_log
    @back_log_window.dispose if @back_log_window != nil
    create_back_log_window
    @status_window.hide
    @party_command_window.deactivate
    @party_command_window.hide
    @back_log_window.refresh
    @back_log_window.activate
    @back_log_window.show
  end
end
