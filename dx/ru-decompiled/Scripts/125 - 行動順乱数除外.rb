class Game_Action
  #--------------------------------------------------------------------------
  # ● 行動速度の計算【再定義】
  #--------------------------------------------------------------------------
  def speed
    speed = subject.agi
    speed += item.speed if item
    speed += subject.atk_speed if attack?
    speed
  end
end

