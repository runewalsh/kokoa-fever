#==============================================================================

module KMS_DetailedItem
  # ◆ デフォルトの所持数上限
  DEFAULT_MAX_NUMBER = 9999
end

#==============================================================================
# ☆ 設定ここまで - END Setting ☆
#==============================================================================

$kms_imported ||= {}
$kms_imported["DetailedItem"] = true

module KMS_DetailedItem
  # デバッグフラグ
  DEBUG = false

  # 所持数上限
  #   記述例 : <所持数上限 30>
  REGEX_MAX_NUMBER = /(?:所持数上限|MAX_NUMBER)\s*(\d+)/i

  #============================================================================
  # □ ItemDetailInfo
  #============================================================================

  class ItemDetailInfo
    #--------------------------------------------------------------------------
    # ○ アクセス修飾子
    #--------------------------------------------------------------------------
    attr_accessor :max_number  # 所持数上限
    #--------------------------------------------------------------------------
    # ○ オブジェクト初期化
    #--------------------------------------------------------------------------
    def initialize(item)
      @item       = item
      @max_number = DEFAULT_MAX_NUMBER
    end
    #--------------------------------------------------------------------------
    # ○ 文字列変換
    #--------------------------------------------------------------------------
    def to_s
      info = [@item.id, @max_number]
      return "アイテム %03d: <max_number=%d>" % info
    end
  end
end

