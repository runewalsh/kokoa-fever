#==============================================================================
# ■ Game_Party
#==============================================================================

class Game_Party < Game_Unit
  #--------------------------------------------------------------------------
  # ● アイテムの最大所持数取得
  #--------------------------------------------------------------------------
  def max_item_number(item)
    if item.is_a?(RPG::BaseItem)
      return item.kms_detail_info.max_number
    else
      return KMS_DetailedItem::DEFAULT_MAX_NUMBER
    end
  end
end
