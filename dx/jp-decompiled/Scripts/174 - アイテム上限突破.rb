#==============================================================================
# ■ RPG::BaseItem
#==============================================================================

class RPG::BaseItem
  #--------------------------------------------------------------------------
  # ○ アイテム詳細情報のキャッシュ作成
  #--------------------------------------------------------------------------
  def kms_create_item_detail_info_cache
    @kms_item_detail_info = KMS_DetailedItem::ItemDetailInfo.new(self)

    note.each_line { |line|
      case line
      when KMS_DetailedItem::REGEX_MAX_NUMBER
        @kms_item_detail_info.max_number = $1.to_i
      end
    }

    if KMS_DetailedItem::DEBUG
      print "#{@kms_item_detail_info.to_s}\n"
    end
  end
  #--------------------------------------------------------------------------
  # ○ アイテム詳細情報の取得
  #--------------------------------------------------------------------------
  def kms_detail_info
    kms_create_item_detail_info_cache if @kms_item_detail_info.nil?
    return @kms_item_detail_info
  end
end

