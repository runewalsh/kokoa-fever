  #--------------------------------------------------------------------------
  # ● TP の初期化【再定義】
  #--------------------------------------------------------------------------
  def init_tp
  end
  #--------------------------------------------------------------------------
  # ● 被ダメージによる TP チャージ【再定義】
  #--------------------------------------------------------------------------
  def charge_tp_by_damage(damage_rate)
    self.tp += TMTPSYSTEM::TP_CHARGE * damage_rate * tcr
  end
end

