module TMTPSYSTEM
  # ダメージ割合に対する TP のチャージ量を設定します
  # この値が 50 で最大ＨＰの半分程度のダメージを受けた場合、TPが25上昇します
  TP_CHARGE = 10
end

#==============================================================================
# ■ Game_Battler
#==============================================================================
